const {test,expect}=require('@playwright/test');
for(const width of [390,768,1440]) test(`caso estético vinculado, apoio e acompanhamento em ${width}px`,async({page})=>{
  await page.setViewportSize({width,height:960});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/#juridico');
  await page.getByRole('button',{name:'Novo caso',exact:false}).click();
  const form=page.locator('#legal-case-form');
  await form.locator('[name=clientId]').selectOption('crm-demo-client-01');
  await expect(form.locator('[name=visitId] option')).toHaveCount(4);
  await form.locator('[name=visitId]').selectOption('crm-demo-visit-01');
  await form.locator('[name=kind]').selectOption('complication');
  await form.locator('[name=summary]').fill('Exemplo fictício <img src=x onerror=alert(1)> para acompanhamento.');
  await form.locator('[name=healthConcern]').check();
  await form.locator('[name=fictional]').check();
  const modal=await page.getByRole('dialog').boundingBox();
  expect(modal.x).toBeGreaterThanOrEqual(0);expect(modal.x+modal.width).toBeLessThanOrEqual(width+1);
  await page.screenshot({path:`.cache/visual/legal-form-${width}.png`});
  await form.getByRole('button',{name:'Salvar caso',exact:true}).click();
  const detail=page.locator('#legal-case-detail');
  await expect(detail).toBeVisible();await expect(detail).toContainText('Prioridade assistencial');
  await expect(detail.locator('.legal-case-summary img')).toHaveCount(0);
  await expect(page.locator('.legal-case-row')).toHaveCount(1);
  await detail.getByRole('button',{name:'Editar caso'}).click();
  await form.locator('[name=fictional]').check();
  await form.locator('[name=deadline]').fill('2026-11-10');
  await form.getByRole('button',{name:'Salvar caso',exact:true}).click();
  await expect(form).toBeVisible();await expect(page.locator('#toast')).toContainText('confirme');
  await form.locator('[name=deadlineChecked]').check();
  await form.locator('[name=kind]').selectOption('lawsuit');
  await form.locator('[name=status]').selectOption('Aguardando advogado');
  await form.locator('[name=doc-record]').check();
  await form.getByRole('button',{name:'Salvar caso',exact:true}).click();
  await expect(page.locator('.legal-case-row')).toHaveCount(1);
  await expect(detail).toContainText('Aguardando advogado');
  await detail.getByRole('button',{name:'Registrar acompanhamento'}).click();
  await page.locator('#legal-case-note-form [name=note]').fill('Exemplo: conferir a comunicação original com assessoria.');
  await page.getByRole('button',{name:'Salvar acompanhamento',exact:true}).click();
  await expect(detail.locator('.legal-case-history')).toContainText('conferir a comunicação');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  await page.screenshot({path:`.cache/visual/legal-case-${width}.png`,fullPage:true});
  await page.reload();
  await page.locator('#legal-cases .section-disclosure-toggle').first().click();
  await page.getByRole('button',{name:'Ver caso e próximos passos'}).click();
  await expect(detail).toContainText('conferir a comunicação');
  await detail.getByRole('button',{name:'Abrir ficha do cliente'}).click();
  await expect(page).toHaveURL(/#crm$/);await expect(page.locator('.crm-profile')).toContainText('Maria');
  await page.getByRole('button',{name:'Excluir cadastro',exact:true}).click();
  await expect(page.locator('#toast')).toContainText('caso de estética vinculado');
  await expect(page.locator('.crm-profile')).toContainText('Maria');
  await page.getByRole('button',{name:'Caso de estética',exact:true}).click();
  await expect(form.locator('[name=clientId]')).toHaveValue('crm-demo-client-01');
  expect(errors).toEqual([]);
});
