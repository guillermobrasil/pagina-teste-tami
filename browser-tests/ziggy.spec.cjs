const {test,expect}=require('@playwright/test');
for(const width of [390,1440]) test(`Ziggy anima e acompanha a conversa em ${width}px`,async({page})=>{
  await page.setViewportSize({width,height:900});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  const posts=[];page.on('request',request=>{if(request.method()==='POST') posts.push(request.url());});
  await page.goto('/#secretaria');
  const ziggy=page.locator('.ziggy-companion');
  await expect(ziggy).toBeVisible(); await expect(ziggy).toHaveAttribute('data-state','idle');
  await expect(page.locator('.ziggy-sprite')).toHaveCSS('background-size','400% 600%');
  await expect(page.locator('#chat-form')).not.toBeVisible();
  await page.getByRole('button',{name:'Conversar com o Ziggy',exact:true}).click();
  const input=page.locator('#chat-input');await expect(input).toBeVisible();
  await input.fill('Como está minha agenda hoje?');
  await expect(ziggy).toHaveAttribute('data-state','listening');
  const start=await page.locator('.ziggy-sprite').evaluate(n=>getComputedStyle(n).backgroundPositionX);
  await page.waitForFunction(start=>getComputedStyle(document.querySelector('.ziggy-sprite')).backgroundPositionX!==start,start);
  await page.screenshot({path:`.cache/visual/ziggy-${width}-listening.png`,fullPage:true});
  await input.press('Enter');
  await expect(ziggy).toHaveAttribute('data-state','thinking');
  await expect(page.locator('.chat-form button')).toBeDisabled();
  await expect(ziggy).toHaveAttribute('data-state','speaking');
  await expect(page.locator('.chat-message')).toHaveCount(2);
  await expect(page.locator('.from-assistant')).toContainText('Avaliação demonstrativa');
  await page.screenshot({path:`.cache/visual/ziggy-${width}-speaking.png`,fullPage:true});
  await input.fill('abacaxi espacial sem assunto');await input.press('Enter');
  await expect(ziggy).toHaveAttribute('data-state','surprised');
  await expect(page.locator('.chat-message')).toHaveCount(4);
  await page.getByRole('button',{name:'Pausar animações',exact:true}).click();
  await expect(page.locator('.ziggy-sprite')).toHaveCSS('animation-name','none');
  await page.getByRole('button',{name:'Retomar animações',exact:true}).click();
  await page.getByRole('button',{name:'Fazer carinho no Ziggy',exact:true}).click();
  await expect(page.locator('.ziggy-status')).toContainText('Um carinho');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('estetica-pro-ia-demo-v1')||'{"chat":[]}').chat)).toEqual([]);
  expect(posts).toEqual([]);expect(errors).toEqual([]);
});
test('Ziggy respeita movimento reduzido e acorda depois de descansar',async({page})=>{
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.clock.install();
  await page.goto('/#secretaria');
  await expect(page.locator('.ziggy-sprite')).toHaveCSS('animation-name','none');
  await page.clock.fastForward(46000);
  await expect(page.locator('.ziggy-companion')).toHaveAttribute('data-state','resting');
  await page.getByRole('button',{name:'Conversar com o Ziggy',exact:true}).click();
  await expect(page.locator('.ziggy-companion')).toHaveAttribute('data-state','idle');
});
test('resposta em preparo não muda a aba escolhida nem duplica perguntas',async({page})=>{
  await page.goto('/#secretaria');
  await page.getByRole('button',{name:'Conversar com o Ziggy',exact:true}).click();
  await page.locator('#chat-input').fill('Como está o financeiro?');await page.locator('#chat-input').press('Enter');
  await expect(page.locator('.ziggy-companion')).toHaveAttribute('data-state','thinking');
  await page.locator('#chat-form').evaluate(form=>{form.requestSubmit();form.requestSubmit();});
  await page.locator('a.nav-item[data-page=agenda]').click();
  await page.waitForFunction(()=>!chatReplyPending);
  await expect(page).toHaveURL(/#agenda$/);
  await page.locator('a.nav-item[data-page=secretaria]').click();
  await expect(page.locator('.chat-message')).toHaveCount(2);
  await expect(page.locator('#chat-input')).toBeEnabled();
  await expect(page.locator('.ziggy-companion')).toHaveAttribute('data-state','idle');
});

